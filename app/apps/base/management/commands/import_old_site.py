class Command(BaseCommand):
    help = 'Переносит тексты со старого сайта resort.baytur.kg.'

    @transaction.atomic
    def handle(self, *args, **options):
        self.import_settings()
        amenities = self.import_amenities()
        self.import_rooms(amenities)
        self.import_services()
        self.import_halls()
        self.import_advantages()
        self.import_about()
        self.import_posts()

        self.stdout.write(self.style.SUCCESS('Тексты со старого сайта перенесены.'))
        self.stdout.write('Фотографии не загружались — их передаёт Заказчик отдельно.')

    def import_settings(self):
        site = SiteSettings.get_solo()
        site.tagline = TAGLINE
        site.address = ADDRESS
        site.legal_name = LEGAL_NAME
        site.seo_description = SEO_DESCRIPTION
        site.save()
        self.stdout.write('  настройки сайта: слоган, адрес, реквизиты')

    def import_amenities(self):
        result = {}
        for order, name in enumerate(AMENITIES):
            result[name], _ = Amenity.objects.get_or_create(name=name, defaults={'order': order})
        self.stdout.write('  удобств: %s' % len(result))
        return result

    def import_rooms(self, amenities):
        for order, item in enumerate(ROOMS):
            slug, name, kind, adults, children, beds, price, description = item
            room, _created = RoomCategory.objects.update_or_create(
                slug=slug,
                defaults={
                    'name': name,
                    'kind': kind,
                    'capacity_adults': adults,
                    'capacity_children': children,
                    'beds': beds,
                    'base_price': Decimal(price),
                    'short_description': description,
                    'description': ROOM_DESCRIPTIONS.get(slug, ''),
                    'order': order,
                    'show_on_home': order < 3,
                    'is_active': True,
                    'total_rooms': 1,
                },
            )
            room.amenities.set(amenities.values())
        self.stdout.write('  категорий номеров: %s' % len(ROOMS))

    def import_services(self):
        for order, (slug, name, description, items) in enumerate(SERVICES):
            category, _ = ServiceCategory.objects.update_or_create(
                slug=slug,
                defaults={'name': name, 'description': description, 'order': order},
            )
            for i, (title, text) in enumerate(items):
                Service.objects.update_or_create(
                    slug='%s-%d' % (slug, i),
                    defaults={
                        'category': category,
                        'name': title,
                        'short_description': text,
                        'order': i,
                    },
                )
        total = sum(len(s[3]) for s in SERVICES)
        self.stdout.write('  категорий услуг: %s, услуг: %s' % (len(SERVICES), total))

    def import_halls(self):
        for order, (slug, name, capacity, description) in enumerate(HALLS):
            ConferenceHall.objects.update_or_create(
                slug=slug,
                defaults={
                    'name': name,
                    'description': '<p>%s</p>' % description,
                    'capacity_theatre': capacity,
                    'order': order,
                },
            )
        self.stdout.write('  конференц-залов: %s' % len(HALLS))

    def import_advantages(self):
        for order, (title, text) in enumerate(ADVANTAGES):
            Advantage.objects.update_or_create(
                title=title, defaults={'description': text, 'order': order},
            )
        self.stdout.write('  преимуществ: %s' % len(ADVANTAGES))

    def import_about(self):
        AboutSection.objects.update_or_create(
            title=ABOUT_TITLE,
            defaults={'content': ABOUT_TEXT, 'order': 0},
        )

        mission = Mission.get_solo()
        mission.eyebrow = 'Наш замысел'
        mission.title = 'Миссия и цели'
        mission.statement = MISSION_STATEMENT
        mission.content = MISSION_TEXT
        mission.is_active = True
        mission.save()

        mission.goals.all().delete()
        for order, (title, text) in enumerate(GOALS):
            MissionGoal.objects.create(
                mission=mission, title=title, description=text, order=order,
            )

        self.stdout.write('  блок «О нас», миссия и %s цели' % len(GOALS))

    def import_posts(self):
        from django.utils.dateparse import parse_date
        from django.utils import timezone
        import datetime

        for order, item in enumerate(POSTS):
            day = parse_date(item['published_at'])
            published = timezone.make_aware(
                datetime.datetime.combine(day, datetime.time(12, 0))
            )
            Post.objects.update_or_create(
                slug=item['slug'],
                defaults={
                    'title': item['title'],
                    'excerpt': item['excerpt'],
                    'content': item['content'],
                    'published_at': published,
                    'order': order,
                },
            )
        self.stdout.write('  новостей: %s' % len(POSTS))
